/* ==========================================================================
   数据边界守卫：外部数据进入领域层前统一收敛结构
   - 后端字段突变（数组变 null / 对象缺失）时返回安全空集合，页面不白屏
   ========================================================================== */

/** 任意值 → 数组；非数组（null / undefined / 对象）一律回退空数组 */
export function asArray<T>(value: unknown): T[] {
  return Array.isArray(value) ? (value as T[]) : []
}
