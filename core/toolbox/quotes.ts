/** 随机取一条；传入上一条可避免连续重复 */
export function pickFooterQuote(
  random: () => number = Math.random,
  exclude = '',
): string {
  if (FOOTER_QUOTES.length === 0) {
    return ''
  }
  const pool = exclude
    ? FOOTER_QUOTES.filter((quote) => quote !== exclude)
    : FOOTER_QUOTES
  const list = pool.length > 0 ? pool : FOOTER_QUOTES
  const value = Math.max(0, Math.min(0.999999, Number(random()) || 0))
  return list[Math.floor(value * list.length)]
}
